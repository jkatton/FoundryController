struct CharOMaticLogoDecoder {
  const uint8_t *p;     // next token to read (PROGMEM)
  uint16_t remaining;   // pixels left in the current run
  uint16_t color;       // the current run's RGB565 color
};

static inline void charOMaticLogoBegin(CharOMaticLogoDecoder &d) {
  d.p = CHAR_O_MATIC_LOGO_RLE;
  d.remaining = 0;
  d.color = 0;
}

// Writes the next `count` pixels of the logo (row-major) into dst as RGB565.
static inline void charOMaticLogoRead(CharOMaticLogoDecoder &d, uint16_t *dst, int count) {
  while (count > 0) {
    if (d.remaining == 0) {
      uint8_t b = pgm_read_byte(d.p++);
      uint8_t v = b & 0x3F;
      d.color = (uint16_t)(((uint16_t)(v >> 1) << 11) | ((uint16_t)v << 5) | (uint16_t)(v >> 1));
      uint8_t code = b >> 6;
      if (code < 3) {
        d.remaining = code + 1;
      } else {
        uint16_t len = 4;
        uint8_t extra;
        do {
          extra = pgm_read_byte(d.p++);
          len += extra;
        } while (extra == 255);
        d.remaining = len;
      }
    }
    uint16_t n = (d.remaining < (uint16_t)count) ? d.remaining : (uint16_t)count;
    for (uint16_t i = 0; i < n; i++) dst[i] = d.color;
    dst += n;
    count -= n;
    d.remaining -= n;
  }
}